// Builds assets/places/<CC>.tsv - the place names drives are named after
// (places.ts) - from GeoNames' per-country extracts, and
// assets/places/index.ts: each country's bounding box and its asset. The
// lists ship with the app as files (metro.config.js), read only when a new
// drive starting or ending in that country is summarised (place-atlas.ts).
// One line per place: name, lat, lon, known - sorted by latitude.
//
//   for c in CZ SK AT DE PL HU; do curl -LO https://download.geonames.org/export/dump/$c.zip && unzip $c.zip $c.txt; done
//   node scripts/make-places.ts CZ.txt SK.txt ...
//
// GeoNames is CC BY 4.0 - credited in the app's About card.
//
// Kept: every populated place (feature class P) - towns, villages and the
// parts of cities (Prague's quarters are PPL entries with their own
// population) - but not historical, abandoned or destroyed ones (PPLH, PPLQ,
// PPLW). Each is marked "known" (1) at 100 people or more: places.ts prefers
// a known place nearby, so a hamlet next to the road does not win over the
// quarter people call it by. Not filtered BY population: GeoNames
// has it for a quarter of Slovak and Polish villages, under a tenth of
// Hungarian ones - a filter left whole regions without a name.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const KNOWN_POP = 100;
const SKIP = new Set(['PPLH', 'PPLQ', 'PPLW']);
const dir = new URL('../assets/places/', import.meta.url);

const files = process.argv.slice(2);
if (!files.length) throw new Error('usage: node scripts/make-places.ts CZ.txt [SK.txt ...]');

for (const src of files) {
  const byCountry = new Map<string, [string, number, number, number][]>();
  for (const line of readFileSync(src, 'utf8').split('\n')) {
    const f = line.split('\t');
    // 1 name, 4 lat, 5 lon, 6 class, 7 code, 8 country, 14 population
    if (f[6] !== 'P' || SKIP.has(f[7])) continue;
    const list = byCountry.get(f[8]) ?? [];
    // 4 decimals: ~11 m, plenty for "which place is nearest".
    list.push([
      f[1],
      Math.round(Number(f[4]) * 1e4) / 1e4,
      Math.round(Number(f[5]) * 1e4) / 1e4,
      Number(f[14]) >= KNOWN_POP ? 1 : 0,
    ]);
    byCountry.set(f[8], list);
  }
  for (const [cc, list] of byCountry) {
    list.sort((a, b) => a[1] - b[1]);   // by latitude: places.ts searches a band
    writeFileSync(new URL(`${cc}.tsv`, dir), list.map((p) => p.join('\t')).join('\n') + '\n');
    console.log(`${cc}: ${list.length} places`);
  }
}

// The index: every country file there is, with its bounding box (a little
// padded, so a drive just over the last village still finds the country).
const PAD = 0.05;
const index: { cc: string; bbox: [number, number, number, number] }[] = [];
for (const f of readdirSync(dir).filter((n) => /^[A-Z]{2}\.tsv$/.test(n)).sort()) {
  let [w, s, e, n] = [180, 90, -180, -90];
  for (const line of readFileSync(new URL(f, dir), 'utf8').trim().split('\n')) {
    const [, lat, lon] = line.split('\t').map(Number);
    w = Math.min(w, lon); s = Math.min(s, lat); e = Math.max(e, lon); n = Math.max(n, lat);
  }
  const r = (x: number) => Math.round(x * 100) / 100;
  index.push({ cc: f.slice(0, 2), bbox: [r(w - PAD), r(s - PAD), r(e + PAD), r(n + PAD)] });
}
// The assets by country: a require of a .tsv is only its asset id - the
// file is read when needed (place-atlas.ts), not held as a module.
writeFileSync(
  new URL('index.ts', dir),
  '// GENERATED by scripts/make-places.ts - do not edit.\n' +
    "import type { AtlasIndex } from '@/lib/places';\n\n" +
    `export const INDEX: AtlasIndex = ${JSON.stringify(index)};\n\n` +
    'export const ASSETS: Record<string, number> = {\n' +
    index.map((c) => `  ${c.cc}: require('./${c.cc}.tsv'),\n`).join('') +
    '};\n',
);
console.log(`index: ${index.map((c) => c.cc).join(' ')}`);
