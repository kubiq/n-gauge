#!/usr/bin/env bash
# Build and optionally flash. Usage:
#   ./scripts/build.sh                  # compile car_gauge_v1
#   ./scripts/build.sh gauge flash      # compile + flash
#
# Flashing deliberately uses esptool with --no-stub rather than
# `arduino-cli upload`. This board's USB-Serial-JTAG dies partway through
# stub-based transfers ("Packet content transfer stopped"), and a failed
# upload leaves the app partition erased - the board then looks bricked
# ("No bootable app partitions") and further uploads report "chip stopped
# responding" because it is reset-looping. --no-stub avoids the whole mess.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PORT="${PORT:-/dev/ttyACM0}"
# USBMode=default = USB-OTG with TinyUSB (2026-10-08), so the firmware can
# offer the SD card as a USB drive alongside serial. It changes how flashing
# gets into download mode - see the flash section at the bottom.
FQBN="esp32:esp32:esp32s3:FlashMode=qio,FlashSize=16M,PartitionScheme=app3M_fat9M_16MB,PSRAM=opi,USBMode=default,CDCOnBoot=cdc"

case "${1:-gauge}" in
  gauge) SKETCH="firmware/car_gauge_v1"; NAME="car_gauge_v1" ;;
  *) echo "usage: $0 [gauge] [flash]"; exit 1 ;;
esac

OUT="$REPO/.build/$NAME"
mkdir -p "$OUT"

# Build stamp for the settings page (ota.cpp), so an OTA-updated pod says
# which firmware it runs. A generated header rather than __DATE__/__TIME__:
# arduino-cli's cache recompiles by file CONTENT, so a source that did not
# change kept its old __TIME__ forever. Rewriting this file changes its
# content, so exactly ota.cpp (its only includer) recompiles.
STAMP="$(date '+%Y-%m-%d %H:%M') $(git -C "$REPO" rev-parse --short HEAD 2>/dev/null || echo nogit)"
git -C "$REPO" diff --quiet HEAD -- "$SKETCH" 2>/dev/null || STAMP="$STAMP+changes"
# One-off test builds: FW_TEST_DEFINE=OTA_CRASH_TEST ./scripts/build.sh
# adds "#define OTA_CRASH_TEST 1" for this build only (the next build drops
# it), and says so in the stamp the settings page shows.
[ -n "${FW_TEST_DEFINE:-}" ] && STAMP="$STAMP TEST:$FW_TEST_DEFINE"
printf '// GENERATED by scripts/build.sh - do not edit, not tracked.\n#define FW_BUILD "%s"\n' \
  "$STAMP" > "$REPO/$SKETCH/build_info.h"
if [ -n "${FW_TEST_DEFINE:-}" ]; then
  printf '#define %s 1   // test build only\n' "$FW_TEST_DEFINE" >> "$REPO/$SKETCH/build_info.h"
fi

echo "==> Compiling $SKETCH ($STAMP)"
# --warnings default: arduino-cli suppresses compiler warnings entirely unless
# asked. That hid a real bug for a while - /api/live's snprintf had seven
# leftover arguments and no placeholders for them, so a counter was passed
# where %s expected a char*, which would have panicked the board the first time
# the endpoint was opened. -Wformat says that plainly; silence did not.
#
# --wrap=get_fattime: FAT file times in UTC - see __wrap_get_fattime() in
# logger.cpp. Without it the card's files show 2 h late on Linux in CEST.
arduino-cli compile --warnings default --fqbn "$FQBN" --output-dir "$OUT" \
  --build-property "compiler.c.elf.extra_flags=-Wl,--wrap=get_fattime" \
  "$REPO/$SKETCH"

[ "${2:-}" = "flash" ] || { echo "==> Not flashing (pass 'flash' to upload)"; exit 0; }

BOOTAPP="$(find "$HOME/.arduino15/packages/esp32" -name boot_app0.bin | head -1)"
[ -n "$BOOTAPP" ] || { echo "ERROR: boot_app0.bin not found"; exit 1; }

# Getting into download mode depends on what the pod runs right now:
# - "USB JTAG/serial debug unit": the ROM bootloader, or an old HWCDC build -
#   esptool's normal DTR/RTS reset works.
# - anything else (the TinyUSB firmware, "ESP32S3_DEV"): esptool's reset is
#   ignored. The core's USBCDC restarts into the ROM bootloader only on the
#   line-state sequence DTR/RTS = 0/1, 1/1, 1/0, 0/0 (cores/esp32/USBCDC.cpp,
#   _onLineState) - send exactly that, then wait for the ROM's JTAG device.
# Either way finish with a WATCHDOG reset: the TinyUSB restart leaves a
# "boot to download mode" flag in RTC memory that the usual RTS reset does
# not clear - on the bench the pod stayed in the bootloader until replugged.
DEV="$(basename "$PORT")"
PRODUCT="$(cat "/sys/class/tty/$DEV/device/../product" 2>/dev/null || true)"
BEFORE="default-reset"
if [ -n "$PRODUCT" ] && [[ "$PRODUCT" != *JTAG* ]]; then
  echo "==> $PORT is '$PRODUCT' (TinyUSB) - requesting the ROM bootloader"
  python3 - "$PORT" <<'EOF'
import serial, sys, time
s = serial.Serial(sys.argv[1], 115200)
for dtr, rts in ((False, True), (True, True), (True, False), (False, False)):
    s.dtr, s.rts = dtr, rts
    time.sleep(0.05)
s.close()
EOF
  for _ in $(seq 1 60); do
    sleep 0.25
    P="$(cat "/sys/class/tty/$DEV/device/../product" 2>/dev/null || true)"
    [[ "$P" == *JTAG* ]] && break
  done
  [[ "${P:-}" == *JTAG* ]] || { echo "ERROR: no ROM bootloader on $PORT - hold BOOT, replug, retry"; exit 1; }
  sleep 0.5
  BEFORE="no-reset"
fi

echo "==> Flashing $NAME to $PORT"
esptool.py --chip esp32s3 --port "$PORT" --baud 115200 --before "$BEFORE" \
  --after watchdog-reset --no-stub write_flash -z \
  0x0     "$OUT/$NAME.ino.bootloader.bin" \
  0x8000  "$OUT/$NAME.ino.partitions.bin" \
  0xe000  "$BOOTAPP" \
  0x10000 "$OUT/$NAME.ino.bin"
